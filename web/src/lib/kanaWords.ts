/** 只用 known 里的假名能写出的词（长音符号ー跟着片假名一起算会） */
export function kanaWordsFor(known: string): Example[] {
  const set = new Set(known);
  const ok = (w: string) => [...w].every((ch) => set.has(ch) || (ch === 'ー' && set.has('ア')));
  const list = W.filter(([w]) => ok(w));
  // 一个假名都还没学（第 0 站）：先从元音开始
  const pool = list.length ? list : W.slice(0, 8);
  return pool.map(([ja, zh]) => ({ ja, reading: ja, zh }));
}
