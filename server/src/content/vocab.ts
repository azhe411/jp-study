/**
 * 词汇量测试题库：按词频分段（VOCAB_FREQUENCY_BANDS）各 10 个真词，另有一组假词。
 * 词频段是按常见度的经验划分，估算本身也只求量级（契约：误差约 ±15%）。
 * 假词看起来像日语、但并不存在 —— 答"认识"就记一次误报，用来校正"全都说认识"的倾向。
 */
import { VOCAB_FREQUENCY_BANDS } from '../../../shared/constants';

export interface VocabWord {
  word: string;
  meaningZh: string;
  /** 所在词频段上界 */
  band: number;
}

const BANDS: string[] = [
  // ≤ 500
  '食べる:吃;行く:去;大きい:大的;水:水;友達:朋友;時間:时间;今日:今天;見る:看;本:书;天気:天气',
  // ≤ 1000
  '料理:菜肴;旅行:旅行;忙しい:忙;部屋:房间;教える:教;病院:医院;約束:约定;便利:方便;季節:季节;答える:回答',
  // ≤ 2000
  '経験:经验;準備:准备;特に:特别;届ける:送到;値段:价格;引っ越す:搬家;迷う:迷路、犹豫;景色:景色;謝る:道歉;最近:最近',
  // ≤ 3000
  '印象:印象;我慢:忍耐;節約:节约;詳しい:详细;募集:招募;担当:负责;状況:状况;比較:比较;改善:改善;怪しい:可疑',
  // ≤ 5000
  '妥協:妥协;慎重:慎重;催促:催促;貢献:贡献;曖昧:暧昧、含糊;克服:克服;渋滞:堵车;抽象:抽象;維持:维持;削除:删除',
  // ≤ 8000
  '踏襲:沿袭;斡旋:斡旋、介绍;懸念:担忧;逸脱:偏离;駆使:运用自如;是正:纠正;払拭:消除;顕著:显著;遡る:追溯;紛糾:纠纷、混乱',
  // ≤ 12000
  '杞憂:杞人忧天;瑕疵:瑕疵;忖度:揣度;齟齬:分歧、龃龉;僥倖:侥幸;逡巡:犹豫不决;恣意:恣意;蹉跌:挫折;敷衍:敷衍、引申;韜晦:韬晦',
  // ≤ 20000
  '囁く:耳语;燻る:冒烟、闷燃;弛緩:松弛;慫慂:怂恿;剽窃:剽窃;揶揄:揶揄;贖罪:赎罪;邂逅:邂逅;矜持:自尊、矜持;嚆矢:嚆矢、开端',
];

export const VOCAB_WORDS: VocabWord[] = BANDS.flatMap((line, i) =>
  line.split(';').map((pair) => {
    const [word, meaningZh] = pair.split(':');
    return { word, meaningZh, band: VOCAB_FREQUENCY_BANDS[i] };
  }),
);

