const HAND_WRITTEN: PhraseDef[] = (Object.entries(BOOKS) as Array<[PhraseBook, Record<string, Row[]>]>).flatMap(
  ([book, categories]) =>
    Object.entries(categories).flatMap(([category, rows]) =>
      rows.map(([ja, reading, zh], i) => ({ slug: `${book}-${category}-${i + 1}`, book, category, ja, reading, zh })),
    ),
);

// v1.7.0：扩充的句子（scripts/genLibrary 生成）。slug 用内容哈希：重新生成或调整顺序都不会张冠李戴
const seen = new Set(HAND_WRITTEN.map((p) => p.ja));
const EXTRA: PhraseDef[] = (GENERATED as Array<{ book: PhraseBook; category: string; ja: string; reading: string; zh: string }>).flatMap((p) => {
  if (seen.has(p.ja)) return [];
  seen.add(p.ja);
  return [{ ...p, slug: `g-${createHash('sha1').update(p.ja).digest('hex').slice(0, 12)}` }];
});

export const BUILTIN_PHRASES: PhraseDef[] = [...HAND_WRITTEN, ...EXTRA];
