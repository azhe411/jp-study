function parse(block: string, level: JlptLevel): Omit<Kanji, 'progress'>[] {
  return block
    .trim()
    .split('\n')
    .map((line) => {
      const [character, strokes, radical, on, kun, meanings, words] = line.split('|');
      const list = (s: string) => (s ? s.split(',') : []);
      return {
        id: `kj-${character}`,
        character,
        onyomi: list(on),
        kunyomi: list(kun),
        meaningsZh: meanings.split('；'),
        strokeCount: Number(strokes),
        radical,
        jlptLevel: level,
        commonWords: words.split(';').map((w) => {
          const [word, reading, meaningZh] = w.split(':');
          return { word, reading, meaningZh };
        }),
      };
    });
}

export const KANJI = parse(N5, 'N5');
export const KANJI_BY_ID = new Map(KANJI.map((k) => [k.id, k]));

/** 训读去掉送假名分隔符后的读音集合（用于判定读音题） */
export function readingsOf(k: Omit<Kanji, 'progress'>): string[] {
  return [...k.onyomi, ...k.kunyomi.map((r) => r.replace('.', '')), ...k.kunyomi.map((r) => r.split('.')[0])];
}
