function topicLessons(topics: Array<[string, string, string]>, part: 'N2' | 'N1'): LessonDef[] {
  return topics.map(([title, goal, points], i) => ({
    id: `${part.toLowerCase()}-${String(i + 1).padStart(2, '0')}`,
    part,
    kind: 'grammar' as const,
    title: `${part} 第 ${i + 1} 站 · ${title}`,
    goal,
    points: points.split('；'),
    pages: [],
    practiceMinutes: 60,
  }));
}

