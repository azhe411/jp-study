export function pageMeta(page: number) {
  return BILI.pages.find((p) => p.page === page);
}

/**
 * 走到每一级累计要投入的小时数（零基础、中文母语，汉字有优势）。
 * 公开的估算差别很大，这里取有汉字背景者的偏低一端，并以 N2 约 1000 小时为锚。
 * 这是总学习量：除了上课，还有背词、复习、听读和备考，不是把课过一遍的时间。
 */
export const CUMULATIVE_HOURS = { N5: 250, N4: 450, N3: 700, N2: 1000, N1: 1700 } as const;

const STAGE_OF_PART: Record<CurriculumPart, keyof typeof CUMULATIVE_HOURS> = { guide: 'N5', kana: 'N5', N5: 'N5', N4: 'N4', N3: 'N3', N2: 'N2', N1: 'N1' };

/** 一课的总学习量（分钟）：把这一级的小时数按上课时长的比例分到每一课 */
const planMinutesOf = new Map<string, number>();

/** 单次上课的预计分钟数：视频 × 1.2（暂停、回看）+ 练习 */
export function lessonMinutes(l: LessonDef): number {
  const video = l.pages.reduce((s, p) => s + (pageMeta(p)?.durationSec ?? 0), 0) / 60;
  return Math.round(video * 1.2 + l.practiceMinutes);
}

{
  const stages = Object.keys(CUMULATIVE_HOURS) as Array<keyof typeof CUMULATIVE_HOURS>;
  stages.forEach((stage, i) => {
    const hours = CUMULATIVE_HOURS[stage] - (i ? CUMULATIVE_HOURS[stages[i - 1]] : 0);
    const lessons = CURRICULUM.filter((l) => STAGE_OF_PART[l.part] === stage);
    const sum = lessons.reduce((s, l) => s + lessonMinutes(l), 0);
    for (const l of lessons) planMinutesOf.set(l.id, (hours * 60 * lessonMinutes(l)) / sum);
  });
}

/** 学习计划用的分钟数：上课 + 背词 + 复习 + 听读 + 备考 */
export function planMinutes(l: LessonDef): number {
  return planMinutesOf.get(l.id)!;
}
